"""執行スタイルと、それが払う（または受け取る）スプレッドの対応。

【なぜ独立したモジュールなのか】

`autotrader.tick` は「スプレッドが**何円か**」を答える。
このモジュールは「そのスプレッドを**払うのか受け取るのか**」を答える。
**別の問いなので、別の場所に置く。**

7家族の実験がすべて「優位 0〜5bps < コスト 5〜13bps」で終わったあと、
`DEFAULT_SPREAD_TICKS` を実測しようとした（意思決定ログ57〜60）。
**だがあれは「何tick払うか」を問うただけで、「払うのか受け取るのか」は
一度も問わなかった**（意思決定ログ102）。

短期リバーサルの利益は価格予測ではなく**流動性供給の対価**として
説明されるのが標準（Nagel 2012）。**その対価を狙いながら、対価の原資である
スプレッドをこちら側が払っていた**のが7家族に共通する構造だった。

【中心にある区別】

::

    往復コスト = スプレッド × (エントリーの取り分 + 手仕舞いの取り分)

取り分は執行スタイルで決まる:

===================  ========  ==================================
スタイル              取り分    根拠
===================  ========  ==================================
成行（板を叩く）        +0.5     最良気配を跨ぐので半値ぶん不利
板寄せ（寄成・引成）     0.0     **単一価格で約定するので跨がない**
指値（気配で待つ）      -0.5     跨いだ相手から半値ぶん受け取る
===================  ========  ==================================

【板寄せが 0.0 になる理由】

板寄せ（オークション）は**全員が同じ1つの価格で約定する**。
最良売気配と最良買気配を跨ぐという行為自体が存在しないので、
スプレッドを払うという概念がない。

**そして我々が測ってきた「始値」はその板寄せの約定価格そのもの。**
寄成で参加すれば、測っている価格ちょうどで建つ——エントリー側の
スリッページは、測定の基準に対して定義上ゼロになる。

**この区別は手法によって効いたり効かなかったりする。**

=========================  ================  ==========================
手法                        エントリー         取り分
=========================  ================  ==========================
前日反転                    **寄成が使える**   **0.0**（板寄せ）
ギャップ・フェード           始値を見てから     +0.5（成行）— 循環するので
                                              板寄せに参加できない
竹（ORB / VWAP乖離）        ザラ場             +0.5（成行）
=========================  ================  ==========================

**執行可能性ゲート（`docs/04-strategies.md`）を通る手法だけが、
このコスト差の恩恵を受けられる。** ゲートを通ることの価値は
「実行できる」だけではなく「安く実行できる」でもあった。

【それでも既定は変えない】

`DEFAULT_ENTRY` は **成行のまま**にしてある。

板寄せが単一価格であることは市場の仕組みなので疑いようがないが、
**「だから始値で建てたのと同じ成績になる」は別の主張**で、まだ実測していない:

- 板寄せの価格は実勢からオーバーシュートする（**実測済み**——始値から
  5分で約19bps戻る・意思決定ログ86）。板寄せで建てるとは、
  そのオーバーシュートした価格で建てるということ
- 寄付の板寄せに自分の注文が本当に間に合うか（Stage A では検証できない）

規約「検証できないものは保守的な側（成績が悪くなる側）に倒す」に従い、
**既定は払う側に置き、板寄せ版は感度として並べる**。
`DEFAULT_SPREAD_TICKS = 2.0` を据え置いたまま感度表を出したのと同じ扱い
（意思決定ログ60）。

【指値（PASSIVE）は日足では測れない】

`EntryStyle.PASSIVE` は**上限の目安**であって、日足から測れる値ではない。
指値が約定するのは「価格がさらにこちらへ動いたとき」＝**自分が間違って
いるときに偏る**（逆選択）。これを入れずに -0.5 をそのまま使うと
成績を必ず過大評価する。

**正しく測るには5分足の約定モデルが要る**（`broker/replay.py`）。
ここでは「もしスプレッドを受け取れたら」の**上限**としてのみ使う。
"""

from __future__ import annotations

from decimal import Decimal
from enum import Enum

from autotrader.tick import DEFAULT_SPREAD_TICKS, spread_yen

__all__ = [
    "DEFAULT_ENTRY",
    "DEFAULT_EXIT",
    "EntryStyle",
    "ExitStyle",
    "round_trip_cost_bps",
    "spread_multiple",
]


class EntryStyle(Enum):
    """建てるときの執行スタイル。値は**スプレッドの何倍を払うか**。"""

    MARKET = 0.5
    """成行で板を叩く。最良気配を跨ぐので半値ぶん不利。"""

    AUCTION = 0.0
    """板寄せ（寄成）に参加する。**単一価格なので跨がない。**

    測っている始値が板寄せの約定価格そのものなので、
    エントリー側のスリッページは測定基準に対して定義上ゼロ。
    **シグナルが前日大引けまでに確定する手法だけが選べる。**
    """

    PASSIVE = -0.5
    """指値を気配に置いて待つ。跨いだ相手から受け取る。

    **日足では測れない上限。** 逆選択（約定するのは自分が間違って
    いるときに偏る）を入れていないので、そのまま使うと必ず過大評価になる。
    """


class ExitStyle(Enum):
    """手仕舞いのときの執行スタイル。値は**スプレッドの何倍を払うか**。"""

    MARKET = 0.5
    """成行で閉じる。**14:50 は待てない**ので、これが既定（安全装置#2）。

    指値で待って未約定なら、翌営業日に強制決済され1注文2,200円
    （目標リターンの約5日分）。**手仕舞いで指値を使わない理由は
    コストではなく安全装置。**
    """

    AUCTION = 0.0
    """引けの板寄せ（引成）で閉じる。

    **安全装置#2（14:50までに閉じる）に反するので既定にしない。**
    大引けは15:30で、そこまで持つと閉じ損ねたときに逃げ場がない。
    """


DEFAULT_ENTRY = EntryStyle.MARKET
"""既定のエントリー。**保守側（払う側）に置いてある**（モジュール冒頭の説明）。"""

DEFAULT_EXIT = ExitStyle.MARKET
"""既定の手仕舞い。**安全装置#2 により、これ以外を選べない。**"""


def spread_multiple(
    entry: EntryStyle = DEFAULT_ENTRY, exit_: ExitStyle = DEFAULT_EXIT
) -> float:
    """往復で払うスプレッドの倍数。**負なら受け取る側。**

    現行の既定（成行 → 成行）は ``1.0`` で、`tick.spread_yen` 1本ぶん。
    これまでの全実験がこの想定で測られている。
    """
    return float(entry.value) + float(exit_.value)


def round_trip_cost_bps(
    price: float,
    *,
    entry: EntryStyle = DEFAULT_ENTRY,
    exit_: ExitStyle = DEFAULT_EXIT,
    n_ticks: float = DEFAULT_SPREAD_TICKS,
    topix100: bool = False,
) -> float:
    """その執行スタイルでの往復コスト（bps）。**負なら受け取る。**

    **スプレッドの円換算は `autotrader.tick` をそのまま使う。**
    コストモデルを診断ごとに作り直さない（意思決定ログ33以降）。

    Raises:
        ValueError: ``price`` が0以下の場合。
    """
    if price <= 0:
        raise ValueError(f"price は0より大きい必要がある: {price}")
    spread: Decimal = spread_yen(price, n_ticks, topix100=topix100)
    return float(spread) * spread_multiple(entry, exit_) / price * 10_000.0
